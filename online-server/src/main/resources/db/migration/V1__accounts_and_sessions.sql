CREATE TABLE accounts (
    id UUID PRIMARY KEY,
    username VARCHAR(24) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    callsign VARCHAR(16) NOT NULL,
    character_id VARCHAR(16) NOT NULL DEFAULT 'male',
    outfit_id VARCHAR(32) NOT NULL DEFAULT 'field',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE profiles (
    account_id UUID PRIMARY KEY REFERENCES accounts(id),
    kills BIGINT NOT NULL DEFAULT 0 CHECK (kills >= 0),
    deaths BIGINT NOT NULL DEFAULT 0 CHECK (deaths >= 0),
    points BIGINT NOT NULL DEFAULT 0 CHECK (points >= 0),
    rounds_played INTEGER NOT NULL DEFAULT 0 CHECK (rounds_played >= 0),
    wins INTEGER NOT NULL DEFAULT 0 CHECK (wins >= 0),
    casual_rating INTEGER NOT NULL DEFAULT 1000,
    ranked_rating INTEGER NOT NULL DEFAULT 1000,
    rank_tier VARCHAR(16) NOT NULL DEFAULT 'UNRANKED'
);
CREATE TABLE owned_weapons (account_id UUID NOT NULL REFERENCES accounts(id), weapon_id VARCHAR(32) NOT NULL, PRIMARY KEY (account_id, weapon_id));
CREATE TABLE weapon_kills (account_id UUID NOT NULL REFERENCES accounts(id), weapon_id VARCHAR(32) NOT NULL, kills BIGINT NOT NULL CHECK (kills >= 0), PRIMARY KEY (account_id, weapon_id));

CREATE TABLE SPRING_SESSION (
    PRIMARY_ID CHAR(36) NOT NULL PRIMARY KEY,
    SESSION_ID CHAR(36) NOT NULL,
    CREATION_TIME BIGINT NOT NULL,
    LAST_ACCESS_TIME BIGINT NOT NULL,
    MAX_INACTIVE_INTERVAL INT NOT NULL,
    EXPIRY_TIME BIGINT NOT NULL,
    PRINCIPAL_NAME VARCHAR(100)
);
CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION (SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION (PRINCIPAL_NAME);
CREATE TABLE SPRING_SESSION_ATTRIBUTES (
    SESSION_PRIMARY_ID CHAR(36) NOT NULL REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE,
    ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
    ATTRIBUTE_BYTES BYTEA NOT NULL,
    PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME)
);
